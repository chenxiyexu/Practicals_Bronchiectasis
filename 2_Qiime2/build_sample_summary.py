import argparse
import sys
import pandas as pd


def parse_tsv(file_path):
    """
    Reads TSV files generated by QIIME 2/ biom convert.
    Handles comment lines (example: "# Constructed from BIOM file") and standardizes
    the sample ID column name to "SampleID".

    Input: 
        file_path (str): Path to the TSV file to be read.
    
    Output:
        pd.DataFrame: DataFrame containing the parsed data with standardized column names.
    """


    #Find the line index where the actual table header starts.
    header_line = 0
    with open(file_path, "r") as f:
        for i, line in enumerate(f):
            if line.startswith("#OTU ID") or line.startswith("#SampleID") or line.startswith("sample-id"):
                header_line = i
                break

    df = pd.read_csv(file_path, sep="\t", skiprows=header_line)
    
    #Standardize sample ID column naming across different QIIME 2 outputs.
    first_col = df.columns[0]
    df.rename(columns={first_col: "SampleID"}, inplace=True)
    df["SampleID"] = df["SampleID"].astype(str).str.strip()
    
    return df


def main():
    """ 
    This script merges metadata, read-tracking statistics, and domain-level assignments 
    into a master summary table.
    
    It is designed to be called from a Bash script, which conditionally passes optional 
    arguments based on the availability of certain files. The script reads the 
    provided TSV files and standardizes column names to ensure consistency across different QIIME 2 outputs.

    Input:
        --metadata: Path to QIIME 2 metadata TSV file (required)
        --output: Path for output master sample summary TSV (required)
        --raw-counts: Path to raw sequence counts TSV (optional)
        --trimmed-counts: Path to trimmed sequence counts TSV (optional)
        --dada2-stats: Path to exported DADA2 denoising stats TSV (optional)  
        --domain-table: Path to exported domain assignment TSV (optional)
    
    Output:
        --output: Path for output master sample summary TSV (required)
    """


    parser = argparse.ArgumentParser(
        description="Merge metadata, read-tracking stats, and domain-level assignments into a master summary table."
    )
    
    #Required arguments.
    parser.add_argument("--metadata", required = True, help = "Path to QIIME 2 metadata TSV file")
    parser.add_argument("--output", required = True, help = "Path for output master sample summary TSV")
    
    #Optional arguments passed conditionally by Bash.
    parser.add_argument("--raw-counts", required = False, help = "Path to raw sequence counts TSV")
    parser.add_argument("--trimmed-counts", required=False, help = "Path to trimmed sequence counts TSV")
    parser.add_argument("--dada2-stats", required = False, help = "Path to exported DADA2 denoising stats TSV")  
    parser.add_argument("--domain-table", required = False, help = "Path to exported domain assignment TSV")
    
    args = parser.parse_args()

    print(f"Python3: Reading metadata from: {args.metadata}")

    try:
        master_df = parse_tsv(args.metadata)
    except Exception as e:
        print(f"Error reading metadata file: {e}", file=sys.stderr)
        sys.exit(1)

    #1. Merge Raw Read Counts (if provided).
    if args.raw_counts:
        print(f"Python3: Merging raw read counts from: {args.raw_counts}")
        raw_df = parse_tsv(args.raw_counts)

        #Assuming table format: SampleID, raw_reads (or count).
        if len(raw_df.columns) >= 2:
            raw_df.columns.values[1] = "raw_reads"
            master_df = master_df.merge(raw_df[["SampleID", "raw_reads"]], on = "SampleID", how = "left")

    #2. Merge Trimmed Read Counts (if provided).
    if args.trimmed_counts:
        print(f"Python3: Merging trimmed read counts from: {args.trimmed_counts}")
        trim_df = parse_tsv(args.trimmed_counts)
        if len(trim_df.columns) >= 2:
            trim_df.columns.values[1] = "trimmed_reads"
            master_df = master_df.merge(trim_df[["SampleID", "trimmed_reads"]], on = "SampleID", how = "left")

    #3. Merge DADA2 Statistics (if provided).
    if args.dada2_stats:
        print(f"Python3: Merging DADA2 stats from: {args.dada2_stats}")
        dada2_df = parse_tsv(args.dada2_stats)

        #Prefix non-SampleID DADA2 columns to prevent collision (e.g. input -> dada2_input)
        dada2_cols = {col: f"dada2_{col}" for col in dada2_df.columns if col != "SampleID"}
        dada2_df.rename(columns=dada2_cols, inplace=True)
        master_df = master_df.merge(dada2_df, on = "SampleID", how = "left")

    #4. Merge Domain Assignment Proportions/ Counts (if provided).
    if args.domain_table:
        print(f"Python3: Merging domain assignments from: {args.domain_table}")
        domain_df = parse_tsv(args.domain_table)
        
        #QIIME 2 biom convert outputs features (Domains) in rows and samples in columns.
        #Check if transpose is needed (if SampleID isn"t the primary index!).
        if "SampleID" in domain_df.columns and len(domain_df) < len(domain_df.columns):
            domain_df = domain_df.set_index("SampleID").T.reset_index()
            domain_df.rename(columns={"index": "SampleID"}, inplace=True)
        
        #Prefix domain columns to distinguish them (e.g., d__Bacteria -> domain_d__Bacteria).
        domain_cols = {col: f"domain_{col}" for col in domain_df.columns if col != "SampleID"}
        domain_df.rename(columns=domain_cols, inplace=True)
        master_df = master_df.merge(domain_df, on = "SampleID", how = "left")

    #Fill NaN values for numeric columns if samples were filtered out during denoising.
    master_df.fillna("N/A", inplace=True)

    #Save final master table.
    master_df.to_csv(args.output, sep = "\t", index = False)
    print(f"Python3: Master sample summary saved to: {args.output}")


if __name__ == "__main__":
    main()